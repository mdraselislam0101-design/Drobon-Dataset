/**
 * app-conformance-md.mjs — render interop/app-conformance.json as a readable
 * divergence register.
 *
 * Kept in a module (not in the generator body) so the prose template is easy to
 * review, and generated (never hand-edited) so it cannot drift from the measured
 * JSON. `scripts/gen-app-conformance.mjs --check` fails when either file stops
 * reproducing.
 */

const pct = (a, b) => (b === 0 ? '—' : `${Math.round((a / b) * 1000) / 10}%`);
const num = (n) => (typeof n === 'number' ? n.toLocaleString('en-US') : String(n));

const escapeCell = (value) => String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ');

const table = (headers, rows) => [
  `| ${headers.join(' | ')} |`,
  `|${headers.map(() => '---').join('|')}|`,
  ...rows.map((row) => `| ${row.map(escapeCell).join(' | ')} |`),
];

export function renderAppConformance(out) {
  const { parity, causes, dastDivergences, languageReachability, loaderChecklist, scaStatusMapping, counting } = out;
  const lines = [];

  lines.push('# APP_CONFORMANCE.md — how the Dataset actually behaves inside the Main App');
  lines.push('');
  lines.push('Generated by `scripts/gen-app-conformance.mjs` from the pack tree and the pinned');
  lines.push('App profile. **Do not edit by hand** — `npm test` fails when this file or');
  lines.push('`interop/app-conformance.json` stops reproducing from the tree.');
  lines.push('');
  lines.push(`- Main App reference: \`${out.generatedFrom.appProfile.repo}\` @ \`${out.generatedFrom.appProfile.commit}\``);
  lines.push(`- Profile source of truth: \`${out.generatedFrom.appProfile.sources.join('`, `')}\` (verified ${out.generatedFrom.appProfile.verifiedAt})`);
  lines.push(`- Packs measured: SAST ${out.generatedFrom.packs.sast} · Secrets ${out.generatedFrom.packs.secrets} · DAST ${out.generatedFrom.packs.dast}`);
  lines.push('- Regenerate: `npm run app-conformance` · verify: `npm run validate:app-conformance`');
  lines.push('');
  lines.push('## 1. Declared-test parity');
  lines.push('');
  lines.push('Every `tests[]` entry in every pack rule is converted and evaluated through a');
  lines.push('transcription of the App loader (`scripts/lib/app-evaluator-profile.mjs`). The');
  lines.push('declared test expectation is the ground truth; the profile only says what the App');
  lines.push('would return for the same input.');
  lines.push('');
  lines.push(...table(
    ['Family', 'Rules', 'Declared tests', 'App accepts', 'Mismatches', 'Parity'],
    [
      ['SAST', num(parity.sast.rules), num(parity.sast.declaredTests), num(parity.sast.acceptedTests), num(parity.sast.mismatches), pct(parity.sast.declaredTests - parity.sast.mismatches, parity.sast.declaredTests)],
      ['Secrets', num(parity.secrets.rules), num(parity.secrets.declaredTests), num(parity.secrets.acceptedTests), num(parity.secrets.mismatches), pct(parity.secrets.declaredTests - parity.secrets.mismatches, parity.secrets.declaredTests)],
      ['DAST', num(parity.dast.rules), num(parity.dast.declaredTests), `${num(parity.dast.acceptedRules)} rules`, num(parity.dast.mismatches), pct(parity.dast.declaredTests - parity.dast.mismatches, parity.dast.declaredTests)],
    ],
  ));
  lines.push('');
  lines.push('SAST and Secrets agree on every declared test: the App would reproduce this');
  lines.push('repository byte-for-byte on those two families. DAST does not, and the exact');
  lines.push('failing set is listed below.');
  lines.push('');

  lines.push('## 2. DAST divergence register (App-side defect)');
  lines.push('');
  const byRule = new Map();
  for (const d of dastDivergences) {
    const entry = byRule.get(d.ruleId) ?? { count: 0, causes: new Set(), tests: [] };
    entry.count += 1;
    entry.causes.add(d.cause);
    entry.tests.push(d.testIndex);
    byRule.set(d.ruleId, entry);
  }
  lines.push(...table(
    ['Rule', 'Check type', 'Failing tests', 'Cause', 'Dataset says', 'App says'],
    [...byRule.entries()].map(([ruleId, entry]) => {
      const first = dastDivergences.find((d) => d.ruleId === ruleId);
      return [
        ruleId,
        first.checkType,
        entry.tests.join(', '),
        [...entry.causes].join(' + '),
        first.datasetExpects,
        first.appYields,
      ];
    }),
  ));
  lines.push('');
  lines.push(`Total: **${num(dastDivergences.length)} divergences on ${num(byRule.size)} rules**, out of ${num(parity.dast.declaredTests)} declared DAST tests.`);
  lines.push('');
  lines.push('Causes (from `interop/app-conformance.json → causes`):');
  lines.push('');
  for (const [name, detail] of Object.entries(causes)) {
    lines.push(`- **${name}** — ${detail}`);
  }
  lines.push('');
  lines.push('Direction of the fix: **the App ports this repository**, not the other way round.');
  lines.push('The dataset keeps the browser-accurate cookie model (`scripts/lib/set-cookie.mjs`),');
  lines.push('treats an all-blank header as absent, and never matches a pattern across a repeated');
  lines.push('header value boundary. Declared tests are unchanged by this register.');
  lines.push('');

  lines.push('## 3. Language reachability');
  lines.push('');
  lines.push(...table(
    ['Measure', 'Value'],
    [
      ['Distinct language ids used by the packs', num(languageReachability.idsUsed)],
      ['Resolved directly by the App catalog', num(languageReachability.resolvedDirectly)],
      ['Resolved through a declared alias', num(languageReachability.resolvedByAlias)],
      ['Need an App family (unresolved)', num(languageReachability.needsAppFamily)],
      ['Universal rules (language-agnostic)', num(languageReachability.universalRules)],
      ['SAST rules reachable at runtime', `${num(languageReachability.rulesReachable)} / ${num(out.generatedFrom.packs.sast)} (${pct(languageReachability.rulesReachable, out.generatedFrom.packs.sast)})`],
      ['SAST rules unreachable at runtime', num(languageReachability.rulesUnreachable)],
    ],
  ));
  lines.push('');
  lines.push('Unreachable rules are not defects in the rules: they cannot fire because the App');
  lines.push('language catalog has no family for their configuration format. The per-id mapping');
  lines.push('lives in `docs/APP_LANGUAGE_ID_MAPPING.md` and is gated by');
  lines.push('`scripts/validate-app-language-ids.mjs`.');
  lines.push('');
  lines.push(`<details><summary>${languageReachability.unreachableRuleIds.length} unreachable rule ids</summary>`);
  lines.push('');
  lines.push(languageReachability.unreachableRuleIds.join(', '));
  lines.push('');
  lines.push('</details>');
  lines.push('');

  lines.push('## 4. App loader checklist (docs/PACKS.md)');
  lines.push('');
  lines.push(...table(
    ['#', 'Requirement', 'Status', 'App evidence', 'Gap'],
    loaderChecklist.map((s) => [s.step, s.requirement, `**${s.status}**`, s.appEvidence, s.gap]),
  ));
  lines.push('');
  const done = loaderChecklist.filter((s) => s.status === 'DONE').length;
  const partial = loaderChecklist.filter((s) => s.status === 'PARTIAL').length;
  const missing = loaderChecklist.filter((s) => s.status === 'MISSING').length;
  lines.push(`Result: ${done} done · ${partial} partial · ${missing} missing. Step 4 (execute`);
  lines.push('declared tests at load) is the structural cause of section 2: a loader that ran');
  lines.push("each rule's own `tests[]` would have refused the disagreeing pack instead of");
  lines.push('shipping it.');
  lines.push('');

  lines.push('## 5. SCA status-surface mapping');
  lines.push('');
  lines.push(...table(
    ['Case', 'Provider dataset status', 'Advisories', 'Scan state', 'Honest meaning'],
    scaStatusMapping.map((r) => [r.case, r.providerDatasetStatus, r.advisories, r.scanState, r.honestMeaning]),
  ));
  lines.push('');
  lines.push('## 6. Counting');
  lines.push('');
  lines.push(...table(
    ['Surface', 'Value', 'Meaning'],
    [
      ['App status surface', num(counting.statusSurfaceReports), 'raw advisory file count reported by the App'],
      ['Canonical identity items', num(counting.canonicalItems), 'docs/COUNTING_POLICY.md'],
      ['Canonical advisory ids', num(counting.canonicalIds), 'docs/COUNTING_POLICY.md'],
    ],
  ));
  lines.push('');
  lines.push(counting.note);
  lines.push('');
  lines.push('## 7. What this register does not say');
  lines.push('');
  lines.push('- It is not a claim that the Dataset works end-to-end in the App: reachability,');
  lines.push('  loader conformance and the remediation surface are still open (see');
  lines.push('  `docs/DATASET_COMPLETION_LEDGER.md`).');
  lines.push('- It does not change any declared pack test, rule, or status in this repository.');
  lines.push('- It is measured against one pinned App commit, not against a released App.');
  lines.push('');
  return `${lines.join('\n')}`;
}
